CREATE DATABASE IF NOT EXISTS IFOOD_DB;
USE IFOOD_DB;

CREATE TABLE IF NOT EXISTS CLIENTE (
    IDCLIENTE INT NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CPF CHAR(11) NOT NULL UNIQUE,
    EMAIL VARCHAR(100) NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    PRIMARY KEY (IDCLIENTE)
);

CREATE TABLE IF NOT EXISTS ENTREGADOR (
    IDENTREGADOR INT NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CPF CHAR(11) NOT NULL UNIQUE,
    TIPO_VEICULO VARCHAR(30) NOT NULL,
    PLACA VARCHAR(10),
    PRIMARY KEY (IDENTREGADOR)
);

SELECT * FROM PEDIDO;

CREATE TABLE IF NOT EXISTS PRODUTO (
    IDPRODUTO INT NOT NULL AUTO_INCREMENT,
    NOME_ITEM VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    PRECO_UNITARIO DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (IDPRODUTO)
);

CREATE TABLE IF NOT EXISTS PEDIDO (
    IDPEDIDO INT NOT NULL AUTO_INCREMENT,
    IDCLIENTE INT NOT NULL,
    IDENTREGADOR INT NOT NULL,
    DATA_HORA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    VALOR_TOTAL DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (IDPEDIDO),
    CONSTRAINT FK_CLIENTE_PEDIDO FOREIGN KEY (IDCLIENTE) REFERENCES CLIENTE(IDCLIENTE),
    CONSTRAINT FK_ENTREGADOR_PEDIDO FOREIGN KEY (IDENTREGADOR) REFERENCES ENTREGADOR(IDENTREGADOR)
);

