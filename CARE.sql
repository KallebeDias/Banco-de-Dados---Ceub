LIMIT 1;

-- RECUPERANDO O ESTADO COM MENOS CIDADE
SELECT * FROM VW_QTD_CIDADE_ESTADO
ORDER BY QTD_CIDADE ASC
LIMIT 1;

-- PEGA O MAIR REGISTRO OU DADO EM COLUNA
SELECT MAX(QTD_CIDADE) FROM VW_QTD_CIDADE_ESTADO;

-- PEGA O MENOR REGISTRO OU DADO EM UMA COLUNA
SELECT MIN(QTD_CIDADE) FROM VW_QTD_CIDADE_ESTADO;

-- AVG -> MÉDIA
SELECT AVG(QTD_CIDADE) FROM VW_QTD_CIDADE_ESTADO;

-- RECUPERANDO ESTADO QUE POSSUEM ENTRE 500 E 600 CIDADES
SELECT * FROM VW_QTD_CIDADE_ESTADO
WHERE QTD_CIDADE BETWEEN 600 AND 800;

