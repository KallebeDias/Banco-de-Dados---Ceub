CREATE TABLE IF NOT EXISTS `CARE`.`ENFERMEIRO_ESPECIALIDADE` (
  `NUM_COREN` SMALLINT NOT NULL,
  `IDESPECIALIDADE` SMALLINT NOT NULL,
  PRIMARY KEY (`NUM_COREN`, `IDESPECIALIDADE`),
  INDEX `fk_ENFERMEIRO_has_ESPECIALIDADE_ESPECIALIDADE1_idx` (`IDESPECIALIDADE` ASC) ,
  INDEX `fk_ENFERMEIRO_has_ESPECIALIDADE_ENFERMEIRO1_idx` (`NUM_COREN` ASC) ,
  CONSTRAINT `fk_ENFERMEIRO_has_ESPECIALIDADE_ENFERMEIRO1`
    FOREIGN KEY (`NUM_COREN`)
    REFERENCES `CARE`.`ENFERMEIRO` (`NUM_COREN`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  CONSTRAINT `fk_ENFERMEIRO_has_ESPECIALIDADE_ESPECIALIDADE1`
    FOREIGN KEY (`IDESPECIALIDADE`)
    REFERENCES `CARE`.`ESPECIALIDADE` (`IDESPECIALIDADE`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION)
ENGINE = InnoDB;


