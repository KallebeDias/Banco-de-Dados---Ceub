-- EXMPLO INTERMEDIÁRIO DE GROUP BY COM COUNT
-- CRIANDO VISUALIZAÇÃO COM CONSULTA INTERMEDIÁRIA
CREATE OR REPLACE VIEW VW_QTD_CIDADE_ESTADO AS
SELECT
    B.DESC_UF AS UF,
    B.NOME_ESTADO_PROVINCIA AS ESTADO,
    COUNT(C.NOMECIDADE) AS QTD_CIDADE
FROM estado_provincia B -- Adicionado a tabela base correta aqui
INNER JOIN cidade C ON B.IDESTADO_PROVINCIA = C.IDESTADO_PROVINCIA
GROUP BY B.DESC_UF, B.NOME_ESTADO_PROVINCIA
ORDER BY QTD_CIDADE DESC;

SELECT * FROM VW_QTD_CIDADE_ESTADO;


-- RECUPERANDO O ESTADO COM MAIS CIDADES
